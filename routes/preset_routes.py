    @ns_preset.route('/<int:user_id>/delete-preset')
    class DeletePresetResource(Resource):
        @api.expect(delete_preset_model)
        @api.response(200, 'Preset deleted successfully', success_message_model)
        @api.response(400, 'Required fields missing', error_response_model_400)
        @api.response(404, 'User, preset not found, or preset does not belong to user', error_response_model_404)
        def delete(self, user_id):
            user = UserSensitiveInformation.query.get(user_id)
            if not user:
                return {"error_code": 404, "message": "User not found"}, 404

            data = request.get_json()
            preset_id = data.get("preset_id")

            if not preset_id:
                return {"error_code": 400, "message": "Preset ID is required"}, 400

            preset = Preset.query.get(preset_id)
            if not preset:
                return {"error_code": 404, "message": "Preset not found"}, 404

            if preset.user_id != user_id:
                return {
                    "error_code": 404, 
                    "message": "This preset does not belong to the specified user"
                }, 404

            try:
                PresetTraveller.query.filter_by(preset_id=preset_id).delete()
                
                db.session.delete(preset)
                db.session.commit()

                return {"message": f"Preset with ID {preset_id} has been deleted successfully"}, 200

            except Exception as e:
                db.session.rollback()
                return {"error_code": 400, "message": f"Error deleting preset: {str(e)}"}, 400


    @ns_preset.route('/create')
    class CreatePresetResource(Resource):
        @api.expect(preset_with_users_model_2)
        @api.response(200, 'Success', preset_response_model)
        @api.response(400, 'Preset name or User ID not given in input', error_response_model_400)
        @api.response(404, 'Creator User ID/Passport number of one of the travellers not found', error_response_model_404)
        def post(self):
            data = request.get_json()

            preset_name = data.get("preset_name")
            user_id = data.get("user_id")
            travellers = data.get("travellers", [])

            if not preset_name:
                return {"error": "Preset name is required"}, 400
            if not user_id:
                return {"error": "User ID is required"}, 400

            creator = UserSensitiveInformation.query.get(user_id)
            if not creator:
                return {"error": f"User with user ID {user_id} not found"}, 404

            new_preset = Preset(preset_name=preset_name, user_id=user_id)
            db.session.add(new_preset)
            db.session.commit()

            preset_id = new_preset.preset_id

            travellers_added = []

            for traveller in travellers:
                passport_number = traveller.get("passport_number")
                given_first_name = traveller.get("first_name")
                given_middle_name = traveller.get("middle_name")
                given_last_name = traveller.get("last_name")

                user_sensitive = UserSensitiveInformation.query.filter_by(passport_number=passport_number).first()
                if not user_sensitive:
                    return {"error": f"Traveller with passport number {passport_number} not found"}, 404

                traveller_user_id = user_sensitive.user_id

                preset_traveller = PresetTraveller(preset_id=preset_id, user_id=traveller_user_id)
                db.session.add(preset_traveller)

                travellers_added.append({
                    "user_id": traveller_user_id,
                    "first_name": given_first_name,
                    "middle_name": given_middle_name,
                    "last_name": given_last_name,
                    "passport_number": passport_number
                })

            db.session.commit()

            response = {
                "preset_id": preset_id,
                "preset_name": preset_name,
                "created_by_user_id": user_id,
                "travellers_added": travellers_added
            }

            return api.marshal(response, preset_response_model), 200
            
    @ns_preset.route('/<int:user_id>/update-preset-travellers-passport')
    class UpdatePresetTravellersPassportResource(Resource):
        @api.expect(update_preset_travellers_passport_model)
        @api.response(200, 'Preset travellers updated successfully', preset_response_model)
        @api.response(400, 'Required fields missing', error_response_model_400)
        @api.response(404, 'User, preset or traveller not found, or preset does not belong to user', error_response_model_404)
        def put(self, user_id):
            user = UserSensitiveInformation.query.get(user_id)
            if not user:
                return {"error_code": 404, "message": "User not found"}, 404

            data = request.get_json()
            preset_id = data.get("preset_id")
            preset_name = data.get("preset_name")
            passport_numbers = data.get("passport_numbers", [])

            if not preset_id:
                return {"error_code": 400, "message": "Preset ID is required"}, 400
            
            if not preset_name:
                return {"error_code": 400, "message": "Preset name is required"}, 400
            
            if not isinstance(passport_numbers, list):
                return {"error_code": 400, "message": "passport_numbers must be a list"}, 400

            preset = Preset.query.get(preset_id)
            if not preset:
                return {"error_code": 404, "message": "Preset not found"}, 404

            if preset.user_id != user_id:
                return {
                    "error_code": 404, 
                    "message": "This preset does not belong to the specified user"
                }, 404

            travellers = []
            for passport_number in passport_numbers:
                traveller = UserSensitiveInformation.query.filter_by(passport_number=passport_number).first()
                if not traveller:
                    return {
                        "error_code": 404, 
                        "message": f"Traveller with passport number {passport_number} not found"
                    }, 404
                travellers.append(traveller)

            try:
                preset.preset_name = preset_name

                PresetTraveller.query.filter_by(preset_id=preset_id).delete()
                
                travellers_added = []
                for traveller in travellers:
                    preset_traveller = PresetTraveller(preset_id=preset_id, user_id=traveller.user_id)
                    db.session.add(preset_traveller)
                    
                    travellers_added.append({
                        "user_id": traveller.user_id,
                        "first_name": traveller.first_name,
                        "middle_name": traveller.middle_name,
                        "last_name": traveller.last_name,
                        "passport_number": traveller.passport_number
                    })
                
                db.session.commit()

                response = {
                    "preset_id": preset_id,
                    "preset_name": preset_name,
                    "created_by_user_id": user_id,
                    "travellers_added": travellers_added
                }

                return api.marshal(response, preset_response_model), 200

            except Exception as e:
                db.session.rollback()
                return {"error_code": 400, "message": f"Error updating preset travellers: {str(e)}"}, 400

    return ns_preset

