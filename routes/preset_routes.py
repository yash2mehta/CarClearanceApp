from flask_restx import Resource, fields
from flask import request
from db_instance import db
from models import UserSensitiveInformation, Preset, PresetTraveller
from api_models import (
    preset_details_model,
    preset_response_model,
    error_response_model_400,
    error_response_model_404,
    success_message_model,
    preset_with_users_model,
    preset_with_users_model_2,
    retrieve_all_presets_for_user_model,
    delete_preset_model,
    update_preset_travellers_passport_model,
    traveller_model_with_user_id
)

def init_preset_routes(api):
    ns_preset = api.namespace('presets', description='Preset-related operations')

    @ns_preset.route('/<int:user_id>/preset-summary')
    class UserPresetsResource(Resource):
        @api.response(200, 'Success', preset_details_model)
        @api.response(404, 'Preset not found', error_response_model_404)
        def get(self, user_id):
            user = UserSensitiveInformation.query.get(user_id)
            if not user:
                return {"error": "User not found"}, 404

            presets = Preset.query.filter_by(user_id=user_id).all()

            presets_list = []
            for p in presets:
                passenger_count = db.session.query(PresetTraveller).filter_by(preset_id=p.preset_id).count()
                
                presets_list.append({
                    "preset_id": p.preset_id,
                    "preset_name": p.preset_name,
                    "passenger_count": passenger_count
                })

            response = {
                "user_id": user_id,
                "presets": presets_list
            }

            return api.marshal(response, preset_details_model), 200


    @ns_preset.route('/<int:user_id>/created-presets-with-users-additional')
    class UserCreatedPresetsWithUsersAdditionalResource(Resource):
        preset_with_users_and_count_model = api.model('PresetWithUsersAndCount', {
            'preset_id': fields.Integer(readonly=True),
            'preset_name': fields.String(required=True, description="Name of the preset"),
            'passenger_count': fields.Integer(required=True, description="Number of passengers in the preset"),
            'users': fields.List(fields.Nested(traveller_model_with_user_id))
        })

        retrieve_all_presets_with_count_model = api.model('AllPresetForUserWithCount', {
            'user_id': fields.Integer(required=True, example=1, description="Autogenerated id of the user"),
            'presets_created': fields.List(fields.Nested(preset_with_users_and_count_model))
        })

        @api.response(200, 'Success', retrieve_all_presets_with_count_model)
        @api.response(404, 'User not found', error_response_model_404)
        def get(self, user_id):
            user = UserSensitiveInformation.query.get(user_id)
            if not user:
                return {"error": "User not found"}, 404

            presets = (
                db.session.query(Preset.preset_id, Preset.preset_name)
                .filter(Preset.user_id == user_id)
                .all()
            )

            if not presets:
                return {"user_id": user_id, "presets_created": []}, 200

            presets_data = []
            for preset_id, preset_name in presets:
                preset_users = (
                    db.session.query(
                        UserSensitiveInformation.user_id,
                        UserSensitiveInformation.first_name,
                        UserSensitiveInformation.middle_name,
                        UserSensitiveInformation.last_name,
                        UserSensitiveInformation.passport_number
                    )
                    .join(PresetTraveller, UserSensitiveInformation.user_id == PresetTraveller.user_id)
                    .filter(PresetTraveller.preset_id == preset_id)
                    .all()
                )

                users_list = [
                    {
                        "user_id": u.user_id,
                        "first_name": u.first_name,
                        "middle_name": u.middle_name,
                        "last_name": u.last_name,
                        "passport_number": u.passport_number
                    }
                    for u in preset_users
                ]

                passenger_count = len(users_list)

                presets_data.append({
                    "preset_id": preset_id,
                    "preset_name": preset_name,
                    "passenger_count": passenger_count,
                    "users": users_list
                })

            response = {
                "user_id": user_id,
                "presets_created": presets_data
            }
            
            return api.marshal(response, self.retrieve_all_presets_with_count_model), 200



